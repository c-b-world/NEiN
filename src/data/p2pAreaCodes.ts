export function formatP2PAreaLabel(areaCode: number, lang: "ja" | "en" | "zh" | "ko" = "ja"): string {
  const info = resolveP2PAreaInfo(areaCode);
  if (!info) {
    if (lang === "en") return `Region Code ${areaCode}`;
    if (lang === "zh") return `地区代码 ${areaCode}`;
    if (lang === "ko") return `지역 코드 ${areaCode}`;
    return `地域コード ${areaCode}`;
  }
  if (info.code === 900) {
    if (lang === "en") return "Unset Region";
    if (lang === "zh") return "未设置地区";
    if (lang === "ko") return "지역 미설정";
    return "地域未設定";
  }
  if (info.code === 901) {
    if (lang === "en") return "Unknown Region";
    if (lang === "zh") return "未知地区";
    if (lang === "ko") return "지역 불명";
    return "地域不明";
  }
  if (info.code === 905) {
    if (lang === "en") return "Outside Japan (Overseas)";
    if (lang === "zh") return "日本以外（海外）";
    if (lang === "ko") return "일본 외 지역(해외)";
    return "日本以外（海外）";
  }
  const reg = lang === "ja" ? info.region : (REGION_I18N[info.region]?.[lang] ?? info.region);
  if (info.name && info.region && !info.name.startsWith(info.region)) {
    return `${reg} · ${info.name}`;
  }
  if (info.name) return info.name;
  if (reg && info.pref) return `${reg} · ${info.pref}`;
  return reg || `Code ${areaCode}`;
}
